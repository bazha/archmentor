export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  let s: string = messages[lang][key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
